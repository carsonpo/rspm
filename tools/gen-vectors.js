// Generates test/vectors/rspm.json: known answers for every RSPM derivation in
// PROTOCOL.md, so independent implementations can check interoperability.
// Inputs come from a fixed seed, so regeneration is byte-identical.
//
// Usage: node tools/gen-vectors.js

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './lib.js';
import { concat, hex, u32be, u64be, utf8 } from '../core/encoding.js';
import { sha256 } from '../core/crypto.js';
import { formatAccountKey, salt, subkeys, deriveKeys } from '../core/kdf.js';
import { locate } from '../core/block.js';
import { retained } from '../core/vault.js';
import { handlePath, hybridSecret, fingerprint } from '../core/share.js';

let counter = 0;
const det = async (n) => {
  const out = [];
  while (out.length < n) out.push(...(await sha256('rspm/vectors', u32be(counter++))));
  return new Uint8Array(out.slice(0, n));
};

const v = { note: 'Generated by tools/gen-vectors.js. All byte strings are hex.' };

v.account_key = [];
for (let i = 0; i < 4; i++) {
  const k = await det(16);
  v.account_key.push({ bytes: hex(k), display: await formatAccountKey(k) });
}

v.salt = [];
for (const u of ['alice', '  Alice ', 'ｆｕｌｌｗｉｄｔｈ', 'Ünïcødé', 'a.b+c@example.com']) {
  v.salt.push({ username: u, salt: hex(await salt(u)) });
}

v.subkeys = [];
for (let i = 0; i < 3; i++) {
  const pw = await det(32), k = await det(16);
  const s = await subkeys(pw, k);
  v.subkeys.push({ argon2_output: hex(pw), account_key: hex(k), loc_key: hex(s.loc), enc_key: hex(s.encRaw) });
}

{
  const k = await det(16);
  const s = await deriveKeys('alice', 'correct horse battery staple', k);
  v.derive_protocol_params = { username: 'alice', password: 'correct horse battery staple', account_key: hex(k),
    argon2: { m: 65536, t: 3, p: 1, len: 32 }, loc_key: hex(s.loc), enc_key: hex(s.encRaw) };
}

v.locators = [];
{
  const key = await det(32), w = await det(16);
  const labels = [
    ['head(1)', concat(utf8('head'), u64be(1))],
    ['head(1000)', concat(utf8('head'), u64be(1000))],
    ['data(7, w, 3)', concat(utf8('data'), u64be(7), w, u32be(3))],
    ['share(0)', concat(utf8('share'), u32be(0))],
    ['keyblock', utf8('keyblock')],
  ];
  for (const [desc, label] of labels) {
    const l = await locate(key, label);
    v.locators.push({ desc, key: hex(key), label: hex(label), token: hex(l.token), locator: l.id });
  }
}

v.retained = [1, 2, 3, 7, 8, 41, 1000, 1023, 1024].map((G) => ({ G, R: [...retained(G)].sort((a, b) => a - b) }));

v.handles = [];
for (const h of ['carson', 'Alice_99', 'x-y-z']) v.handles.push({ handle: h, path: await handlePath(h) });

{
  const [ssx, ssk, eph, ct, xpk, ek] = [await det(32), await det(32), await det(32), await det(1088), await det(32), await det(1184)];
  v.hybrid = { ss_x: hex(ssx), ss_k: hex(ssk), eph_pk: hex(eph), ct_k: hex(ct), x_pk: hex(xpk), ek: hex(ek),
    s: hex(await hybridSecret(ssx, ssk, eph, ct, xpk, ek)), fingerprint: await fingerprint(xpk, ek) };
}

writeFileSync(join(root, 'test/vectors/rspm.json'), JSON.stringify(v, null, 1) + '\n');
console.log('wrote test/vectors/rspm.json');
